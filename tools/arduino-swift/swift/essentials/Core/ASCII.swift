enum ASCII {
    static let space: Byte = 0x20
    static let tab: Byte = 0x09
    static let lf: Byte = 0x0A
    static let cr: Byte = 0x0D

    static let quote: Byte = 0x22
    static let backslash: Byte = 0x5C
    static let slash: Byte = 0x2F
    static let colon: Byte = 0x3A
    static let comma: Byte = 0x2C
    static let lbrace: Byte = 0x7B
    static let rbrace: Byte = 0x7D
    static let lbracket: Byte = 0x5B
    static let rbracket: Byte = 0x5D
}
